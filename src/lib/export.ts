import type { ChatEntry } from "../stores/chatStore";
import { compareSources, compareToMarkdown } from "./compare";
import type { ResearchSource } from "./events";

export type ExportFormat = "markdown" | "html" | "pdf" | "json";

export interface ResearchReportData {
  title: string;
  query?: string;
  createdAt: number;
  model?: string;
  content: string;
  sources: ResearchSource[];
  metrics?: {
    durationMs?: number | null;
    tokens?: number;
    tokensPerSec?: number;
    ttftMs?: number;
  };
}

/** Trigger download of a text blob in the browser */
export function downloadFile(content: string, filename: string, mimeType: string): void {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement("a");
  anchor.href = url;
  anchor.download = filename;
  document.body.appendChild(anchor);
  anchor.click();
  document.body.removeChild(anchor);
  URL.revokeObjectURL(url);
}

/** Formats a research run into a clean, comprehensive Markdown report */
export function generateMarkdownReport(data: ResearchReportData): string {
  const dateStr = new Date(data.createdAt).toLocaleString();
  const lines: string[] = [
    `# Research Report: ${data.title}`,
    ``,
    `> **Generated by Local Research Agent**`,
    `> Date: ${dateStr}  `,
    `> Model: \`${data.model ?? "Local Model"}\`  `,
  ];

  if (data.metrics?.durationMs) {
    const sec = (data.metrics.durationMs / 1000).toFixed(1);
    lines.push(`> Execution Time: ${sec}s  `);
  }
  if (data.metrics?.tokensPerSec) {
    lines.push(`> Generation Speed: ${data.metrics.tokensPerSec.toFixed(1)} tokens/sec  `);
  }

  lines.push(``, `---`, ``, `## Synthesis & Findings`, ``, data.content, ``);

  if (data.sources.length > 0) {
    lines.push(`---`, ``, `## Cited Sources & Bibliography`, ``);
    lines.push(`| # | Title | Domain | Engine | URL |`);
    lines.push(`|---|-------|--------|--------|-----|`);
    for (const src of data.sources) {
      const sanitizedTitle = src.title.replace(/\|/g, "-");
      const readBadge = src.read ? "*(read)*" : "*(snippet)*";
      lines.push(
        `| [${src.id}] | ${sanitizedTitle} ${readBadge} | \`${src.domain || "web"}\` | ${src.engine || "searxng"} | [Link](${src.url}) |`,
      );
    }
    lines.push(``);
  }

  if (data.sources.length > 1) {
    lines.push(`## Cross-source overlap`, ``);
    lines.push(
      `Overlap counts significant terms shared between titles and snippets. It is a reading aid, not a verdict on which page is correct.`,
      ``,
    );
    lines.push(compareToMarkdown(compareSources(data.sources)), ``);
  }

  lines.push(`---`, `*Generated offline on local hardware with zero cloud telemetry.*`);

  return lines.join("\n");
}

/** Formats a research run into a standalone, printable HTML document */
export function generateHtmlReport(data: ResearchReportData): string {
  const dateStr = new Date(data.createdAt).toLocaleString();
  const escapeHtml = (text: string) =>
    text
      .replace(/&/g, "&amp;")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;")
      .replace(/"/g, "&quot;")
      .replace(/'/g, "&#039;");

  const sourcesList = data.sources
    .map(
      (src) => `
      <li style="margin-bottom: 12px; padding: 10px; background: #f8fafc; border: 1px solid #e2e8f0; border-radius: 8px;">
        <div style="display: flex; justify-content: space-between; align-items: baseline; margin-bottom: 4px;">
          <strong>[${src.id}] ${escapeHtml(src.title)}</strong>
          <span style="font-size: 12px; color: #64748b; background: #e2e8f0; padding: 2px 6px; border-radius: 4px;">${escapeHtml(src.domain || "web")}</span>
        </div>
        <p style="margin: 4px 0; font-size: 13px; color: #475569;">${escapeHtml(src.snippet)}</p>
        <a href="${escapeHtml(src.url)}" target="_blank" rel="noopener noreferrer" style="font-size: 12px; color: #0284c7; text-decoration: underline; word-break: break-all;">${escapeHtml(src.url)}</a>
      </li>`,
    )
    .join("");

  const comparisonRows = compareSources(data.sources)
    .map(
      (row) => `
      <tr>
        <td style="padding: 6px 8px; border-bottom: 1px solid #e2e8f0; font-weight: 600;">[${row.source.id}] ${escapeHtml(row.source.title)}</td>
        <td style="padding: 6px 8px; border-bottom: 1px solid #e2e8f0; color: #64748b;">${escapeHtml(row.source.domain || "web")}</td>
        <td style="padding: 6px 8px; border-bottom: 1px solid #e2e8f0; text-align: right;">${row.bestShared}</td>
        <td style="padding: 6px 8px; border-bottom: 1px solid #e2e8f0;">${row.peers.length ? row.peers.map((id) => `[${id}]`).join(" ") : "unique"}</td>
      </tr>`,
    )
    .join("");

  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <title>Research Dossier - ${escapeHtml(data.title)}</title>
  <style>
    body {
      font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif;
      max-width: 840px;
      margin: 40px auto;
      padding: 0 24px;
      color: #1e293b;
      line-height: 1.6;
    }
    header {
      border-bottom: 2px solid #0284c7;
      padding-bottom: 16px;
      margin-bottom: 24px;
    }
    h1 { margin: 0 0 8px 0; color: #0f172a; font-size: 26px; }
    .meta { font-size: 13px; color: #64748b; }
    .badge { background: #e0f2fe; color: #0369a1; padding: 2px 8px; border-radius: 12px; font-weight: 600; font-size: 12px; }
    .findings {
      background: #ffffff;
      padding: 16px 0;
      white-space: pre-wrap;
      font-size: 15px;
    }
    ol.sources { padding-left: 0; list-style: none; }
    footer { margin-top: 40px; padding-top: 16px; border-top: 1px solid #e2e8f0; font-size: 12px; color: #94a3b8; text-align: center; }
    @media print {
      body { margin: 20px auto; max-width: 100%; }
      a { text-decoration: none; color: #000; }
    }
  </style>
</head>
<body>
  <header>
    <span class="badge">Local Research Agent Dossier</span>
    <h1>${escapeHtml(data.title)}</h1>
    <div class="meta">
      <span>Date: ${escapeHtml(dateStr)}</span> &bull;
      <span>Model: ${escapeHtml(data.model || "Local")}</span>
      ${data.metrics?.durationMs ? `&bull; <span>Time: ${(data.metrics.durationMs / 1000).toFixed(1)}s</span>` : ""}
    </div>
  </header>

  <section>
    <h2>Synthesis &amp; Response</h2>
    <div class="findings">${escapeHtml(data.content)}</div>
  </section>

  ${
    data.sources.length > 0
      ? `
  <section style="margin-top: 32px;">
    <h2>Cited References (${data.sources.length})</h2>
    <ol class="sources">
      ${sourcesList}
    </ol>
  </section>`
      : ""
  }

  ${
    data.sources.length > 1
      ? `
  <section style="margin-top: 32px;">
    <h2>Cross-source overlap</h2>
    <p style="font-size: 12px; color: #64748b;">Shared significant terms between titles and snippets. A reading aid, not a verdict on which page is correct.</p>
    <table style="width: 100%; border-collapse: collapse; font-size: 13px;">
      <thead>
        <tr style="text-align: left; color: #64748b; font-size: 11px; text-transform: uppercase; letter-spacing: 0.06em;">
          <th style="padding: 6px 8px; border-bottom: 1px solid #cbd5e1;">Source</th>
          <th style="padding: 6px 8px; border-bottom: 1px solid #cbd5e1;">Domain</th>
          <th style="padding: 6px 8px; border-bottom: 1px solid #cbd5e1; text-align: right;">Max shared</th>
          <th style="padding: 6px 8px; border-bottom: 1px solid #cbd5e1;">Related</th>
        </tr>
      </thead>
      <tbody>${comparisonRows}</tbody>
    </table>
  </section>`
      : ""
  }

  <footer>
    Generated by Local Research Agent &bull; 100% Offline &bull; No Cloud Telemetry
  </footer>
</body>
</html>`;
}

/**
 * Open the styled dossier in the platform print dialog, where it can be saved
 * as PDF. This avoids shipping a PDF engine: the webview already renders the
 * report, so the operating system's own PDF writer produces the file.
 *
 * Returns false when the webview has no print implementation, so the caller can
 * fall back to downloading the HTML.
 */
export function printReportAsPdf(data: ResearchReportData): boolean {
  const html = generateHtmlReport(data).replace(
    "</style>",
    `    @page { size: A4; margin: 16mm; }
    body { max-width: none; margin: 0; padding: 0; }
    li { break-inside: avoid; }
  </style>`,
  );

  const frame = document.createElement("iframe");
  frame.setAttribute("aria-hidden", "true");
  frame.title = "Research dossier print view";
  Object.assign(frame.style, {
    position: "fixed",
    right: "0",
    bottom: "0",
    width: "0",
    height: "0",
    border: "0",
    opacity: "0",
    pointerEvents: "none",
  });
  document.body.appendChild(frame);

  const cleanup = () => {
    window.setTimeout(() => frame.remove(), 60_000);
  };

  frame.onload = () => {
    const target = frame.contentWindow;
    if (!target || typeof target.print !== "function") {
      frame.remove();
      downloadFile(html, `research-report-${Date.now()}.html`, "text/html");
      return;
    }
    window.setTimeout(() => {
      target.focus();
      target.print();
      cleanup();
    }, 250);
  };
  frame.srcdoc = html;
  return true;
}

/** Formats a full conversation or research item to JSON */
export function generateJsonExport(entries: ChatEntry[]): string {
  return JSON.stringify(
    {
      exportedAt: new Date().toISOString(),
      agent: "Local Research Agent v0.2.2",
      conversation: entries.map((entry) => ({
        id: entry.id,
        role: entry.role,
        content: entry.content,
        mode: entry.mode,
        model: entry.model,
        createdAt: entry.createdAt,
        sources: entry.sources ?? [],
      })),
    },
    null,
    2,
  );
}
